#include <stdio.h>
#include <math.h>
#include <locale.h>

int main() {
    setlocale(LC_ALL, "Russian");
    
    /* 
     * Объявление переменных:
     * x   - значение аргумента, вводимое пользователем
     * y   - искомое значение функции (результат вычислений)
     * a1  - промежуточная переменная (числитель аргумента косинуса)
     * b1  - промежуточная переменная (знаменатель аргумента косинуса)
     */
    long double x;
    long double y;
    long double a1;
    long double b1;
    
    printf("Введите значение x: ");
    scanf_s("%Lf", &x); 
    
    // Проверка: является ли введённое пользователем значение x положительным числом.
    // Если x > 0 - выводим сообщение об успехе, иначе - предупреждение о том, что значение не положительное.
    if (x > 0) {
        printf("Переменная x положительна: x = %Lf\n", x);
    } else {
        printf("Внимание! Переменная x не положительна: x = %Lf\n", x);
    }
    
    a1 = 3.2 + sqrtl(1 + x); 
    b1 = fabsl(5 * x); 
    
    y = cos(a1 / b1); 
    
    printf("Искомое значение y = %Lf", y); 
    
    return 0;
}
